export interface PetTierStyle {
  tier: 'gold' | 'purple' | 'blue' | 'green';
  border: string;
  bg: string;
  text: string;
  badgeBg: string;
  shadow: string;
  label: string;
}

export function getPetTierStyle(petNameOrQuality?: string): PetTierStyle {
  const str = (petNameOrQuality || '').toLowerCase();

  // SSR / Gold / ตำนาน
  if (
    str.includes('ssr') ||
    str.includes('gold') ||
    str.includes('ตำนาน') ||
    str.includes('skoll') ||
    str.includes('dusk') ||
    str.includes('rita') ||
    str.includes('เฟียร์ส') ||
    str.includes('dawn') ||
    str.includes('ฟลอร่า') ||
    str.includes('มีญ่า') ||
    str.includes('alice')
  ) {
    return {
      tier: 'gold',
      border: 'border-amber-400 dark:border-amber-500/70',
      bg: 'bg-amber-50 dark:bg-amber-950/20',
      text: 'text-amber-800 dark:text-amber-300',
      badgeBg: 'bg-gradient-to-r from-amber-500/20 to-orange-500/20 text-amber-900 dark:text-amber-200 border-amber-500/50',
      shadow: 'shadow-amber-500/10',
      label: 'Pet SSR',
    };
  }

  // SR / Purple / อีพิค
  if (
    str.includes('sr') ||
    str.includes('purple') ||
    str.includes('ม่วง') ||
    str.includes('อีพิค') ||
    str.includes('baphomet') ||
    str.includes('deviruchi') ||
    str.includes('pudding') ||
    str.includes('gryphon') ||
    str.includes('mammoth') ||
    str.includes('golem') ||
    str.includes('garm baby') ||
    str.includes('sohee') ||
    str.includes('piamette') ||
    str.includes('squidgitte') ||
    str.includes('medusa')
  ) {
    return {
      tier: 'purple',
      border: 'border-purple-400 dark:border-purple-500/70',
      bg: 'bg-purple-50 dark:bg-purple-950/20',
      text: 'text-purple-800 dark:text-purple-300',
      badgeBg: 'bg-gradient-to-r from-purple-500/20 to-fuchsia-500/20 text-purple-900 dark:text-purple-200 border-purple-500/50',
      shadow: 'shadow-purple-500/10',
      label: 'Pet SR',
    };
  }

  // R / Blue / ฟ้า / แรร์
  if (
    str.includes('r') ||
    str.includes('blue') ||
    str.includes('ฟ้า') ||
    str.includes('แรร์') ||
    str.includes('wolf') ||
    str.includes('marionette') ||
    str.includes('siroma') ||
    str.includes('bigfoot') ||
    str.includes('seal') ||
    str.includes('solider') ||
    str.includes('marina') ||
    str.includes('whisper') ||
    str.includes('obeaune')
  ) {
    return {
      tier: 'blue',
      border: 'border-sky-400 dark:border-sky-500/70',
      bg: 'bg-sky-50 dark:bg-sky-950/20',
      text: 'text-sky-800 dark:text-sky-300',
      badgeBg: 'bg-gradient-to-r from-sky-500/20 to-blue-500/20 text-sky-900 dark:text-sky-200 border-sky-500/50',
      shadow: 'shadow-sky-500/10',
      label: 'Pet R',
    };
  }

  // N / Green / เขียว / ทั่วไป
  return {
    tier: 'green',
    border: 'border-emerald-400 dark:border-emerald-500/70',
    bg: 'bg-emerald-50 dark:bg-emerald-950/20',
    text: 'text-emerald-800 dark:text-emerald-300',
    badgeBg: 'bg-gradient-to-r from-emerald-500/20 to-teal-500/20 text-emerald-900 dark:text-emerald-200 border-emerald-500/50',
    shadow: 'shadow-emerald-500/10',
    label: 'Pet N',
  };
}
